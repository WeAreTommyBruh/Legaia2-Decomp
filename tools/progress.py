#!/usr/bin/env python3
"""Writes PROGRESS.md: how far the decompilation has come.

Reads decomp/functions.csv (Ghidra export), asm/*.s (tools/asm_build.py
split), build/SLES_508.91 (asm_build.py build) and src/ (functions rewritten
in C; a matched function is marked with a `// MATCH func_XXXXXXXX` comment
just before it). The file lists only counts, sizes and source file names.

Usage: progress.py [OUT.md]       (default PROGRESS.md)
"""

import collections
import csv
import datetime
import glob
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def pct(a, b):
    if not b:
        return "-"
    return f"{100 * a / b:.2f}%" if 0 < a / b < 0.01 else f"{100 * a / b:.1f}%"


def bar(a, b, width=30):
    n = round(width * a / b) if b else 0
    return "`" + "#" * n + "." * (width - n) + "`"


def main(argv):
    out = argv[1] if len(argv) > 1 else os.path.join(ROOT, "PROGRESS.md")
    with open(os.path.join(ROOT, "decomp", "functions.csv")) as f:
        funcs = list(csv.DictReader(f))
    matched = set()
    for path in glob.glob(os.path.join(ROOT, "src", "**", "*.c"), recursive=True):
        matched |= {int(a, 16) for a in re.findall(r"//\s*MATCH\s+func_([0-9A-Fa-f]{8})", open(path).read())}

    total = len(funcs)
    size = sum(int(r["size_bytes"]) for r in funcs)
    named = [r for r in funcs if not r["name"].startswith("FUN_") and "_00" not in r["name"]]
    attributed = [r for r in funcs if r["source_file"]]
    m_funcs = [r for r in funcs if int(r["address"], 16) in matched]
    def marked(pattern):
        out = set()
        for path in glob.glob(os.path.join(ROOT, "src", pattern, "*.c")):
            out |= {int(a, 16) for a in re.findall(r"//\s*MATCH\s+func_([0-9A-Fa-f]{8})", open(path).read())}
        return out
    generated, from_ghidra = marked("gen"), marked("ghidra")
    m_size = sum(int(r["size_bytes"]) for r in m_funcs)

    words = instr = 0
    for path in glob.glob(os.path.join(ROOT, "asm", "[0-9]*.s")):
        for line in open(path):
            if line.startswith("    "):
                words += 1
                instr += not line.startswith("    .word")

    status = "not built yet (run tools/asm_build.py all)"
    exe, built = os.path.join(ROOT, "disc", "SLES_508.91"), os.path.join(ROOT, "build", "SLES_508.91")
    if os.path.exists(exe) and os.path.exists(built):
        same = hashlib.sha1(open(exe, "rb").read()).digest() == hashlib.sha1(open(built, "rb").read()).digest()
        status = "**byte-identical** to the original" if same else "**differs** from the original"

    by_file = collections.defaultdict(lambda: [0, 0, 0, 0])
    for r in funcs:
        key = r["source_file"] or "(not attributed)"
        e = by_file[key]
        e[0] += 1
        e[1] += int(r["size_bytes"])
        e[2] += int(r["address"], 16) in matched
        e[3] += int(r["size_bytes"]) if int(r["address"], 16) in matched else 0

    L = []
    L.append("# Decompilation progress\n\n")
    L.append(f"Generated by `tools/progress.py` on {datetime.date.today().isoformat()}. "
             "Counts only; no game code or data.\n\n")
    L.append("This is not a matching decompilation. \"Matched\" below means C that happens to "
             "compile to exactly the original bytes (what ByteMatch counts); the rest of the "
             "project (Ghidra output, named functions, decoded file formats) is not counted.\n\n")
    L.append("## Steps\n\n")
    L.append("| # | Step | Status |\n|---|---|---|\n")
    L.append("| 1 | Identify the original compiler | Done: **ee-gcc 2.9-ee-991111-01**, `-O2 -G8`, "
             "confirmed by functions that compile byte-identical (see below) |\n")
    L.append(f"| 2 | Rebuild the executable from assembly | Done: rebuilt executable is {status} |\n")
    L.append(f"| 3 | Match functions in C | In progress: {len(m_funcs)} of {total} functions "
             f"({pct(m_size, size)} of code) compile to the original bytes and are built from C |\n")
    L.append("\n## Overall\n\n")
    L.append("| | Count | Share | |\n|---|---:|---:|---|\n")
    L.append(f"| Functions matched in C | {len(m_funcs)} / {total} | {pct(len(m_funcs), total)} | {bar(len(m_funcs), total)} |\n")
    L.append(f"| ... written by hand | {len(matched - generated - from_ghidra)} | | |\n")
    L.append(f"| ... generated from instruction patterns (`tools/gen_tiny.py`) | {len(generated)} | | |\n")
    L.append(f"| ... Ghidra's decompilation, already matching (`tools/gen_ghidra.py`) | {len(from_ghidra)} | | |\n")
    L.append(f"| Code bytes matched in C | {m_size:,} / {size:,} | {pct(m_size, size)} | {bar(m_size, size)} |\n")
    L.append(f"| Functions with a source file | {len(attributed)} / {total} | {pct(len(attributed), total)} | {bar(len(attributed), total)} |\n")
    L.append(f"| Functions with a real name | {len(named)} / {total} | {pct(len(named), total)} | {bar(len(named), total)} |\n")
    if words:
        L.append(f"| .text words disassembled as instructions | {instr:,} / {words:,} | {pct(instr, words)} | {bar(instr, words)} |\n")
    L.append("\nFunctions with a source file come from the game's `__FILE__` debug strings; real names "
             "are the descriptive and library names given in `ghidra/scripts/NameFunctions.java`. "
             "The remaining .text words are EE-only instructions (128-bit loads/stores, multimedia, "
             "VU0 macro mode), written as `.word` because clang cannot assemble them.\n")
    L.append("\n## Compiler\n\n")
    L.append("- The code is GCC output: libgcc's soft-float routines (`__unpack_f`, `__adddf3`, ...) "
             "are linked in and C++ type names use GCC's length-prefixed form (`11Accelerator`). "
             "There are no SN Systems (ProDG) or Metrowerks strings.\n")
    L.append("- The SDK libraries are Runtime Library 2.5.0 (`PsIIlib... 2500` strings), but the game "
             "code itself was built with the older EE GCC 2.9 (1999) rather than the SDK's 2.96. "
             "Compiling the same C with the builds from decomp.me's archive:\n")
    L.append("  - ee-gcc 2.96 saves registers in 8-byte stack slots; the game uses 16-byte slots "
             "(about 2,500 functions show this), so it is ruled out.\n")
    L.append("  - ee-gcc 2.9-ee-990721 and 2.9-ee-991111 put a `nop` between `mtc1` and `cvt.s.w` "
             "that the game does not have.\n")
    L.append("  - ee-gcc 2.9-ee-991111-01 (and 991111a, which reports the same version) reproduce "
             "every matched function. The build uses 991111-01.\n")
    L.append("- Flags: `-O2 -G8`. Float constants are loaded gp-relative from `.lit4` and the gp "
             "value (0x4a7c70) comes from `.reginfo`.\n")
    L.append("\n## How matching works\n\n")
    L.append("- `src/*.c` holds the functions rewritten in C. A matched function has a "
             "`// MATCH func_XXXXXXXX` comment just before it; one that compiles but does not match "
             "yet stays under `#ifdef NONMATCHING`, and the build uses the original assembly.\n")
    L.append("- `src/gen/` is written by `tools/gen_tiny.py`: tiny functions (empty functions, "
             "constants, field and global getters/setters) translated from their instructions; only "
             "exact matches are kept.\n")
    L.append("- `src/ghidra/` is written by `tools/gen_ghidra.py`: Ghidra's own decompilation, with "
             "only types and global names adjusted, for the functions where it already compiles to "
             "the original bytes. It reads like Ghidra output and is meant to be cleaned up by hand.\n")
    L.append("- Every check resolves relocations to the real addresses (functions, `D_XXXXXXXX` "
             "globals, gp-relative offsets), so a call or global access to the wrong place counts "
             "as a difference.\n")
    L.append("- `python3 tools/report.py` writes the objdiff report `report/report.json` that "
             "ByteMatch reads.\n")
    L.append("- `python3 tools/match.py src/FILE.c NAME ADDRESS` compiles the file and compares one "
             "function word by word with the original.\n")
    L.append("- `python3 tools/asm_build.py all` rebuilds the executable from the assembly plus the "
             "matched C, and checks it is byte-identical.\n")
    L.append("\n## By source file\n\n")
    L.append("| Source file | Functions | Code bytes | Matched | Matched bytes |\n|---|---:|---:|---:|---:|\n")
    for key, (n, b, m, mb) in sorted(by_file.items(), key=lambda kv: (kv[0].startswith("("), kv[0])):
        L.append(f"| `{key}` | {n} | {b:,} | {m} | {pct(mb, b)} |\n")
    with open(out, "w") as f:
        f.writelines(L)
    print(f"wrote {out}: {len(m_funcs)}/{total} matched, {len(attributed)} attributed, {len(named)} named")


if __name__ == "__main__":
    main(sys.argv)

#!/usr/bin/env python3
"""Writes PROGRESS.md: how far the matching decompilation has come.

Reads decomp/functions.csv (Ghidra export), asm/*.s (tools/asm_build.py
split), build/SLES_508.91 (asm_build.py build) and src/ (functions rewritten
in C; a matched function is marked with a `// MATCH func_XXXXXXXX` comment
just before it). The file lists only counts, sizes and source file names.

Usage: progress.py [OUT.md]       (default PROGRESS.md)
"""

import collections
import csv
import datetime
import glob
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "-"


def bar(a, b, width=30):
    n = round(width * a / b) if b else 0
    return "`" + "#" * n + "." * (width - n) + "`"


def main(argv):
    out = argv[1] if len(argv) > 1 else os.path.join(ROOT, "PROGRESS.md")
    with open(os.path.join(ROOT, "decomp", "functions.csv")) as f:
        funcs = list(csv.DictReader(f))
    matched = set()
    for path in glob.glob(os.path.join(ROOT, "src", "**", "*.c"), recursive=True):
        matched |= {int(a, 16) for a in re.findall(r"//\s*MATCH\s+func_([0-9A-Fa-f]{8})", open(path).read())}

    total = len(funcs)
    size = sum(int(r["size_bytes"]) for r in funcs)
    named = [r for r in funcs if not r["name"].startswith("FUN_") and "_00" not in r["name"]]
    attributed = [r for r in funcs if r["source_file"]]
    m_funcs = [r for r in funcs if int(r["address"], 16) in matched]
    m_size = sum(int(r["size_bytes"]) for r in m_funcs)

    words = instr = 0
    for path in glob.glob(os.path.join(ROOT, "asm", "[0-9]*.s")):
        for line in open(path):
            if line.startswith("    "):
                words += 1
                instr += not line.startswith("    .word")

    status = "not built yet (run tools/asm_build.py all)"
    exe, built = os.path.join(ROOT, "disc", "SLES_508.91"), os.path.join(ROOT, "build", "SLES_508.91")
    if os.path.exists(exe) and os.path.exists(built):
        same = hashlib.sha1(open(exe, "rb").read()).digest() == hashlib.sha1(open(built, "rb").read()).digest()
        status = "**byte-identical** to the original" if same else "**differs** from the original"

    by_file = collections.defaultdict(lambda: [0, 0, 0, 0])
    for r in funcs:
        key = r["source_file"] or "(not attributed)"
        e = by_file[key]
        e[0] += 1
        e[1] += int(r["size_bytes"])
        e[2] += int(r["address"], 16) in matched
        e[3] += int(r["size_bytes"]) if int(r["address"], 16) in matched else 0

    L = []
    L.append("# Decompilation progress\n\n")
    L.append(f"Generated by `tools/progress.py` on {datetime.date.today().isoformat()}. "
             "Counts only; no game code or data.\n\n")
    L.append("## Steps\n\n")
    L.append("| # | Step | Status |\n|---|---|---|\n")
    L.append("| 1 | Identify the original compiler | Done: GCC-based SCE toolchain, most likely "
             "**ee-gcc 2.96** (see below) |\n")
    L.append(f"| 2 | Rebuild the executable from assembly | Done: rebuilt executable is {status} |\n")
    L.append(f"| 3 | Match functions in C | {len(m_funcs)} of {total} functions "
             f"({pct(m_size, size)} of code); needs ee-gcc 2.96 installed |\n")
    L.append("\n## Overall\n\n")
    L.append("| | Count | Share | |\n|---|---:|---:|---|\n")
    L.append(f"| Functions matched in C | {len(m_funcs)} / {total} | {pct(len(m_funcs), total)} | {bar(len(m_funcs), total)} |\n")
    L.append(f"| Code bytes matched in C | {m_size:,} / {size:,} | {pct(m_size, size)} | {bar(m_size, size)} |\n")
    L.append(f"| Functions with a source file | {len(attributed)} / {total} | {pct(len(attributed), total)} | {bar(len(attributed), total)} |\n")
    L.append(f"| Functions with a real name | {len(named)} / {total} | {pct(len(named), total)} | {bar(len(named), total)} |\n")
    if words:
        L.append(f"| .text words disassembled as instructions | {instr:,} / {words:,} | {pct(instr, words)} | {bar(instr, words)} |\n")
    L.append("\nFunctions with a source file come from the game's `__FILE__` debug strings; real names "
             "are the descriptive and library names given in `ghidra/scripts/NameFunctions.java`. "
             "The remaining .text words are EE-only instructions (128-bit loads/stores, multimedia, "
             "VU0 macro mode), written as `.word` because clang cannot assemble them.\n")
    L.append("\n## Compiler\n\n")
    L.append("- The SDK libraries linked in are Runtime Library 2.5.0 (`PsIIlib... 2500` version "
             "strings), and the disc was mastered in September 2002. That SDK shipped with SCE's "
             "ee-gcc 2.96.\n")
    L.append("- The code is GCC output: libgcc's soft-float routines (`__unpack_f`, `__adddf3`, ...) "
             "are linked in and C++ type names use GCC's length-prefixed form (`11Accelerator`). "
             "There are no SN Systems (ProDG) strings, and `.DVP` overlay sections come from SCE's "
             "`dvp-as`.\n")
    L.append("- Float constants are loaded gp-relative from `.lit4`, and `.sdata`/`.sbss` exist, so "
             "it was built with a non-zero `-G` (small-data size).\n")
    L.append("- Confirming 2.96 (and the exact flags) means compiling a few functions and comparing; "
             "that is the first job of step 3.\n")
    L.append("\n## By source file\n\n")
    L.append("| Source file | Functions | Code bytes | Matched | Matched bytes |\n|---|---:|---:|---:|---:|\n")
    for key, (n, b, m, mb) in sorted(by_file.items(), key=lambda kv: (kv[0].startswith("("), kv[0])):
        L.append(f"| `{key}` | {n} | {b:,} | {m} | {pct(mb, b)} |\n")
    with open(out, "w") as f:
        f.writelines(L)
    print(f"wrote {out}: {len(m_funcs)}/{total} matched, {len(attributed)} attributed, {len(named)} named")


if __name__ == "__main__":
    main(sys.argv)

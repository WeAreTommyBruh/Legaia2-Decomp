#!/usr/bin/env python3
"""Battle camera/action scripts (data/battle/*.bsd).

Interpreter: FUN_00144910 (0x00144910). Each command is a float opcode followed
by float parameters. Opcodes 0-3 are control codes: 0 ends a track, 3 marks the
frame the following commands run on (FUN_00151930 finds the commands for a
frame), 1 and 2 are track/condition switches.

Opcode table at 0x0032ef48, 93 records of 0x8c bytes:
  const char **name; int category; int param_count;
  struct { const char **value_names; int type; float min, max; } params[8];
type 8 = vec3 (3 floats), otherwise 1 float. Names are the game's own
script-editor labels.

.bsd layout (loader noribs_00151c60 @ 0x00151c60):
  u32 track_count (<= 32); 3 words the loader ignores;
  u32 track_offset[track_count] (bytes from file start);
  each track: u32 float_count, float data[float_count].

Usage:
  battle_script.py opcodes EXE                 markdown opcode reference
  battle_script.py disasm EXE FILE.bsd [...]   readable listing
  battle_script.py check EXE FILE.bsd [...]    parse every track, report problems
"""

import struct
import sys

SECTIONS = ((0x2F7080, 0x1F8080, 0x133E94), (0x42AF80, 0x32BF80, 0x74C48), (0x4A1080, 0x3A2080, 0x5AF0))
TABLE, RECORD, COUNT = 0x32EF48, 0x8C, 0x5D
VEC3 = 8


class Opcode:
    def __init__(self, op, name, category, params):
        self.op, self.name, self.category, self.params = op, name, category, params

    def width(self):
        return sum(3 if p["type"] == VEC3 else 1 for p in self.params)


def load_opcodes(exe_path):
    elf = open(exe_path, "rb").read()

    def off(va):
        for base, o, size in SECTIONS:
            if base <= va < base + size:
                return va - base + o
        return None

    def u32(va):
        o = off(va)
        return None if o is None else struct.unpack_from("<I", elf, o)[0]

    def cstr(va):
        o = off(va)
        return None if o is None else elf[o:elf.index(b"\0", o)].decode("latin1").strip()

    def f32(w):
        return struct.unpack("<f", struct.pack("<I", w))[0]

    ops = {}
    for op in range(COUNT):
        w = struct.unpack_from("<35I", elf, off(TABLE + op * RECORD))
        name = cstr(u32(w[0])) if w[0] and u32(w[0]) else ""
        name = name.replace("%c2", "").replace("%c6", "")
        params = []
        for i in range(w[2]):
            names_ptr, ty, lo, hi = w[3 + 4 * i:7 + 4 * i]
            values = None
            if names_ptr:
                values = []
                for k in range(int(f32(hi)) + 1):
                    s = u32(names_ptr + 4 * k)
                    values.append(cstr(s) if s else "?")
            params.append({"type": ty, "min": f32(lo), "max": f32(hi), "values": values})
        ops[op] = Opcode(op, name, w[1], params)
    return ops


def is_unused(o):
    return o.op > 3 and o.name == "END OF SCRIPT" and not o.params


def tracks(data):
    count = struct.unpack_from("<I", data, 0)[0]
    for i in range(count):
        off = struct.unpack_from("<I", data, 16 + 4 * i)[0]
        n = struct.unpack_from("<I", data, off)[0]
        yield i, list(struct.unpack_from(f"<{n}f", data, off + 4))


def decode_track(floats, ops):
    """Yields (index, opcode or None, args); raises ValueError on bad data."""
    i = 0
    while i < len(floats):
        op = int(floats[i])
        if floats[i] != op or op not in ops or is_unused(ops[op]):
            raise ValueError(f"bad opcode {floats[i]!r} at float {i}")
        o = ops[op]
        args = floats[i + 1:i + 1 + o.width()]
        if len(args) < o.width():
            raise ValueError(f"truncated {o.name} at float {i}")
        yield i, o, args
        i += 1 + o.width()
        if op == 0:
            return


def format_args(o, args):
    out, k = [], 0
    for p in o.params:
        if p["type"] == VEC3:
            out.append("(" + ", ".join(f"{v:g}" for v in args[k:k + 3]) + ")")
            k += 3
        else:
            v = args[k]
            k += 1
            if p["values"] and v == int(v) and 0 <= int(v) < len(p["values"]):
                out.append(p["values"][int(v)])
            else:
                out.append(f"{v:g}")
    return ", ".join(out)


def label(o):
    return o.name.split("%")[0].strip()


def cmd_opcodes(ops):
    print("# Battle script opcodes\n")
    print("Generated by `tools/battle_script.py opcodes` from the table at `0x0032ef48`.")
    print("Each command is a float opcode followed by float parameters; `vec3` takes 3 floats.\n")
    print("| Op | Name | Cat | Parameters |")
    print("| --- | --- | --- | --- |")
    for o in ops.values():
        if is_unused(o):
            continue
        params = []
        for p in o.params:
            s = ("vec3" if p["type"] == VEC3 else "num") + f" {p['min']:g}..{p['max']:g}"
            if p["values"]:
                s += " (" + ", ".join(p["values"]) + ")"
            params.append(s)
        print(f"| 0x{o.op:02x} | `{o.name.replace('|', '/')}` | {o.category} | {'; '.join(params)} |")


def main(argv):
    if len(argv) < 3 or argv[1] not in ("opcodes", "disasm", "check"):
        raise SystemExit(__doc__)
    ops = load_opcodes(argv[2])
    if argv[1] == "opcodes":
        cmd_opcodes(ops)
        return
    bad = 0
    for path in argv[3:]:
        data = open(path, "rb").read()
        if argv[1] == "disasm":
            print(f"; {path}")
        for t, floats in tracks(data):
            try:
                cmds = list(decode_track(floats, ops))
            except ValueError as e:
                bad += 1
                print(f"{path}: track {t}: {e}")
                continue
            if argv[1] == "disasm":
                print(f"track {t}:")
                for i, o, args in cmds:
                    print(f"  {i:4d}  {label(o):<18} {format_args(o, args)}")
    if argv[1] == "check":
        print(f"checked {len(argv) - 3} files, {bad} bad tracks")


if __name__ == "__main__":
    main(sys.argv)
